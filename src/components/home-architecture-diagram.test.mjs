  assert.match(diagramSource, /const DIAGRAM_HEIGHT = 760/)
  assert.match(diagramSource, /const DIAGRAM_WIDTH = 1448/)
  assert.match(diagramSource, /width: 1208,/)
  assert.match(diagramSource, /lines: \['数据统一接入'\]/)
  assert.match(diagramSource, /lines: \['数据资源管控'\]/)
  assert.match(diagramSource, /lines: \['数据安全管控'\]/)
  assert.match(diagramSource, /lines: \['数据应用管控'\]/)
  assert.match(diagramSource, /lines: \['数据共享管控'\]/)
  assert.match(diagramSource, /lines: \['数据仓库'\]/)
  assert.match(diagramSource, /lines: \['数据中台'\]/)
  assert.match(diagramSource, /lines: \['应用系统'\]/)
  assert.match(diagramSource, /lines: \['数据统一接入'\],\s*\n\s*}\s*,\s*\n\s*{\s*\n\s*id: 'governance-catalog'/)
  assert.match(diagramSource, /lines: \['数据资源目录'\]/)
  assert.match(diagramSource, /lines: \['数据API'\]/)
  assert.match(diagramSource, /lines: \['分类分级'\]/)
  assert.match(diagramSource, /lines: \['访问策略'\]/)
  assert.match(diagramSource, /lines: \['共享策略'\]/)
  assert.match(diagramSource, /lines: \['应用管理'\]/)
  assert.match(diagramSource, /lines: \['应用需求'\]/)
  assert.match(diagramSource, /lines: \['外部需求'\]/)
  assert.match(diagramSource, /lines: \['同域访问'\]/)
  assert.match(diagramSource, /lines: \['跨域访问'\]/)
  assert.match(diagramSource, /lines: \['同态加密'\]/)
  assert.match(diagramSource, /node\.lines\.slice\(0, 3\)/)
  assert.match(diagramSource, /node\.lines\.slice\(3\)/)
  assert.match(diagramSource, />\s*供给\s*</)
  assert.match(diagramSource, />\s*需求\s*</)
  assert.match(diagramSource, /数据来源一本账/)
  assert.match(diagramSource, /数据资源一本账/)
  assert.match(diagramSource, /安全策略一本账/)
