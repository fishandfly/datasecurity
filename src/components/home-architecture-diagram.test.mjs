import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const diagramSource = readFileSync(resolve(process.cwd(), 'src/components/home-architecture-diagram.tsx'), 'utf8')
const homePageSource = readFileSync(resolve(process.cwd(), 'src/pages/home-page.tsx'), 'utf8')
const indexCssSource = readFileSync(resolve(process.cwd(), 'src/index.css'), 'utf8')

test('首页接入总体架构示意图组件', () => {
  assert.match(homePageSource, /import \{ HomeArchitectureDiagram \} from '\.\.\/components\/home-architecture-diagram'/)
  assert.match(homePageSource, /<HomeArchitectureDiagram \/>/)
})

